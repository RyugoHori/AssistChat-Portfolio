-- ----------------------------------------------------------------------------
-- IVFFLAT インデックス作成
-- 
-- IVFFLAT: 近似最近傍探索（ANN）アルゴリズムの一種
-- 
-- パラメータ:
--   - lists = 100: クラスター数
--     目安: データ件数の平方根（√10000 ≈ 100）
--     1万件の場合、lists=100 が最適
-- 
--   - vector_cosine_ops: コサイン距離演算子
--     正規化済みベクトルのコサイン類似度計算に最適
-- 
-- 注意:
--   - データが空の状態では作成できない
--   - インデックス作成には数秒〜数十秒かかる（データ量による）
-- ----------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS documents_embedding_idx 
    ON documents USING ivfflat (embedding vector_cosine_ops)
    WITH (lists = 100);

-- ----------------------------------------------------------------------------
-- 統計情報の更新
-- 
-- VACUUM ANALYZE の役割:
--   - テーブルの統計情報を更新
--   - クエリプランナーが最適な実行計画を選択できるようになる
--   - 検索パフォーマンスが向上
-- 
-- 実行タイミング:
--   - インデックス作成後
--   - 大量データ挿入後
--   - 定期的なメンテナンス
-- ----------------------------------------------------------------------------
VACUUM ANALYZE documents;

-- ----------------------------------------------------------------------------
-- インデックス情報コメント
-- ----------------------------------------------------------------------------
COMMENT ON INDEX documents_embedding_idx IS 'ベクトル類似度検索用IVFFLATインデックス。lists=100（1万件最適化）';
